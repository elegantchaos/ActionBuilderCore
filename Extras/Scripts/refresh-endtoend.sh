#!/usr/bin/env bash
set -euo pipefail

SOURCE="${BASH_SOURCE[0]}"
while [ -L "$SOURCE" ]
do
    SCRIPT_DIR="$(cd -P "$(dirname "$SOURCE")" && pwd)"
    SOURCE="$(readlink "$SOURCE")"
    case "$SOURCE" in
        /*) ;;
        *) SOURCE="$SCRIPT_DIR/$SOURCE" ;;
    esac
done

SCRIPT_DIR="$(cd -P "$(dirname "$SOURCE")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
PACKAGE_DIR="$REPO_ROOT/Tests/EndToEndTests"
GENERATED_WORKFLOW_DIR="$PACKAGE_DIR/.github/workflows"
GENERATED_CALLER="$GENERATED_WORKFLOW_DIR/EndToEndTests.yml"
GENERATED_SWIFT_HELPER="$GENERATED_WORKFLOW_DIR/EndToEndSwiftJob.yml"
GENERATED_XCODE_HELPER="$GENERATED_WORKFLOW_DIR/EndToEndXcodeJob.yml"
ROOT_WORKFLOW_DIR="$REPO_ROOT/.github/workflows"
GATE_TEMPLATE="$SCRIPT_DIR/endtoend-current-job.yml"

cd "$REPO_ROOT"

swift build --product swift-ci
"$REPO_ROOT/.build/debug/swift-ci" generate "$PACKAGE_DIR"

mv "$GENERATED_WORKFLOW_DIR/SwiftWorkflowBuilderSwiftJob.yml" "$GENERATED_SWIFT_HELPER"
mv "$GENERATED_WORKFLOW_DIR/SwiftWorkflowBuilderXcodeJob.yml" "$GENERATED_XCODE_HELPER"

# The generated files are stamped with the tool version, which comes from the latest git tag
# when the tool is built, so it can't take part in a stable generated-file comparison:
# tagging a release would make the committed files stale. Replace the stamp with a fixed
# artificial one. The pattern also accepts a trailing build number, as older stamps had.
# It only matches a stamp that has a version, so a missing or malformed stamp still fails
# the freshness check. The real version being inserted correctly is covered by GeneratorTests.
perl -0pi -e '
    s/(automatically generated by SwiftWorkflowBuilder) \S+(?: \([^)]+\))?\./$1 0.0.0./g;
' "$GENERATED_CALLER" "$GENERATED_SWIFT_HELPER" "$GENERATED_XCODE_HELPER"

perl -0pi -e '
    s/SwiftWorkflowBuilderSwiftJob\.yml/EndToEndSwiftJob.yml/g;
    s/SwiftWorkflowBuilderXcodeJob\.yml/EndToEndXcodeJob.yml/g;
    s/^(  [A-Za-z0-9_-]+:\n)(    name:)/$1    needs: generated-workflows-current\n$2/mg;
' "$GENERATED_CALLER"

GENERATED_JOB_COUNT=$(awk '/^jobs:$/ { in_jobs = 1; next } /^[^ ]/ { in_jobs = 0 } in_jobs && /^  [A-Za-z0-9_-]+:$/ { count++ } END { print count + 0 }' "$GENERATED_CALLER")
DEPENDENT_JOB_COUNT=$(awk '$0 == "    needs: generated-workflows-current" { count++ } END { print count + 0 }' "$GENERATED_CALLER")
if [[ "$GENERATED_JOB_COUNT" -eq 0 || "$GENERATED_JOB_COUNT" -ne "$DEPENDENT_JOB_COUNT" ]]
then
    echo "Failed to make every generated EndToEnd job depend on the freshness gate." >&2
    exit 1
fi

perl -0pi -e '
    s/(    runs-on: \$\{\{ inputs\.runner \}\}\n)/$1    defaults:\n      run:\n        working-directory: Tests\/EndToEndTests\n/;
' "$GENERATED_SWIFT_HELPER" "$GENERATED_XCODE_HELPER"

END_TO_END_GATE_TEMPLATE="$GATE_TEMPLATE" perl -0pi -e '
    BEGIN {
        local $/;
        open my $template, "<", $ENV{END_TO_END_GATE_TEMPLATE} or die $!;
        $gate = <$template>;
        close $template;
    }
    s/^jobs:\n/"jobs:\n$gate\n"/me;
' "$GENERATED_CALLER"

mkdir -p "$ROOT_WORKFLOW_DIR"
cp "$GENERATED_CALLER" "$ROOT_WORKFLOW_DIR/EndToEndTests.yml"
cp "$GENERATED_SWIFT_HELPER" "$ROOT_WORKFLOW_DIR/EndToEndSwiftJob.yml"
cp "$GENERATED_XCODE_HELPER" "$ROOT_WORKFLOW_DIR/EndToEndXcodeJob.yml"

echo "Refreshed EndToEnd workflows in: $ROOT_WORKFLOW_DIR"
